// Stand-in numerals and symbols for characters the handwriting photo didn't contain (0-9 and a few signs).
// They are PEN glyphs: centre-line strokes drawn with the same marker width as the outlined letters, so they
// sit in the same hand. Replace them when digits are added to the font (see Claude/2026-10-09_handwriting-font).
// Units are font units (1000 per em), y up, baseline at 0.

const rad = (d) => (d * Math.PI) / 180;
/** points on an ellipse, angles in degrees, counter-clockwise positive; a0 -> a1 may go either way */
const arc = (cx, cy, rx, ry, a0, a1, step = 12) => {
  const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / step));
  const out = [];
  for (let i = 0; i <= n; i++) {
    const a = rad(a0 + ((a1 - a0) * i) / n);
    out.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return out;
};
const flat = (pts) => pts.flatMap((p) => [Math.round(p[0]), Math.round(p[1])]);
const G = (w, ...strokes) => ({ w, pen: true, s: strokes.map(flat) });

