// Generates presets.bundled.js from presets/*.frag so the viewer can run as a
// fully static web page (no server) with the seed presets baked in.
// Run:  node build-presets.mjs   (the server also runs this automatically on save/delete)

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const dir = join(__dirname, "presets");

export async function buildBundle() {
  const files = (await readdir(dir)).filter((f) => f.endsWith(".frag")).sort();
  const presets = await Promise.all(
    files.map(async (f) => {
      const code = await readFile(join(dir, f), "utf8");
      const m = code.match(/^\/\/\s*name:\s*(.+)$/m);
      const g = code.match(/^\/\/\s*group:\s*(.+)$/m);
      return {
        id: f.replace(/\.frag$/, ""),
        name: m ? m[1].trim() : f.replace(/\.frag$/, ""),
        group: g ? g[1].trim() : "Other",
        code,
      };
    })
  );
  const out =
    "// AUTO-GENERATED by build-presets.mjs — do not edit by hand.\n" +
    "window.BUNDLED_PRESETS = " +
    JSON.stringify(presets, null, 2) +
    ";\n";
  await writeFile(join(__dirname, "presets.bundled.js"), out, "utf8");
  return presets.length;
}

// run directly (handles paths with spaces via proper file-URL comparison)
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const n = await buildBundle();
  console.log(`Wrote presets.bundled.js with ${n} preset(s).`);
}
